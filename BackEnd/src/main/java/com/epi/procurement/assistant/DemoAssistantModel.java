package com.epi.procurement.assistant;

import java.util.Locale;

import org.springframework.stereotype.Component;

/**
 * Deterministic local adapter for tests and demo. Never contacts an external model.
 */
@Component
class DemoAssistantModel implements AssistantModel {

	static final String LABEL = "Demo response — not generated by a live AI model.";

	@Override
	public Completion complete(Prompt prompt) {
		String q = prompt.userQuestion() == null ? "" : prompt.userQuestion().toLowerCase(Locale.ROOT);
		String data = prompt.retrievedDataBlock() == null ? "" : prompt.retrievedDataBlock();
		if (q.contains("ignore previous") || q.contains("disregard system") || data.toLowerCase(Locale.ROOT)
			.contains("ignore previous instructions")) {
			return new Completion(LABEL + "\n\nRetrieved text was treated as untrusted data. No tools or audience were "
					+ "changed.\n\n" + truncate(data), "SAFE_REFUSAL", false, null, null);
		}
		if (containsAny(q, "draft", "follow-up", "follow up", "ask the supplier", "message to supplier")) {
			String draft = extractDraft(data);
			return new Completion(LABEL + "\n\n**Draft** (not sent). Review before using in messaging.\n\nRecorded "
					+ "context used for the draft excludes internal notes.\n\n" + truncate(data), "DRAFT", true,
					"EXTERNAL", draft);
		}
		if (containsAny(q, "summar", "dossier", "history")) {
			return new Completion(LABEL + "\n\n**Summary of authorised records**\n\n" + truncate(data)
					+ "\n\n_Missing fields are omitted rather than invented._", "SUMMARIZE", false, null, null);
		}
		if (containsAny(q, "where", "status", "explain", "owner", "who")) {
			return new Completion(LABEL + "\n\n**Status (recorded facts)**\n\n" + truncate(data), "EXPLAIN", false, null,
					null);
		}
		if (containsAny(q, "find", "list", "which", "awaiting", "po", "purchase order", "request")) {
			return new Completion(LABEL + "\n\n**Matches in your scope**\n\n" + truncate(data), "FIND", false, null,
					null);
		}
		return new Completion(LABEL + "\n\nI can find authorised requests/POs, explain recorded status, summarise a "
				+ "dossier, or draft an EXTERNAL supplier follow-up for your review.\n\n" + truncate(data), "HELP",
				false, null, null);
	}

	private static String extractDraft(String data) {
		StringBuilder draft = new StringBuilder(
				"Hello,\n\nCould you please provide an update on the open points below?\n\n");
		for (String line : data.split("\n")) {
			String trimmed = line.trim();
			if (trimmed.startsWith("EXTERNAL:") || trimmed.startsWith("- EXTERNAL")) {
				draft.append("• ").append(trimmed.replaceFirst("^(?:- )?EXTERNAL:\\s*", "")).append('\n');
			}
		}
		if (draft.toString().endsWith("below?\n\n")) {
			draft.append("• Please confirm lead time and packing details.\n");
		}
		draft.append("\nThank you.");
		return draft.toString();
	}

	private static boolean containsAny(String haystack, String... needles) {
		for (String n : needles) {
			if (haystack.contains(n)) {
				return true;
			}
		}
		return false;
	}

	private static String truncate(String text) {
		if (text == null || text.isBlank()) {
			return "_No authorised records matched this question._";
		}
		return text.length() <= 4000 ? text : text.substring(0, 3990) + "…";
	}

}
