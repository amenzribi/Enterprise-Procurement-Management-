import { expect, test } from '@playwright/test';
import { USERS, signIn, t } from './support';

test('buyer assistant demo mode answers with labelled demo text (EN)', async ({ page }) => {
  await signIn(page, USERS.buyer, 'en', '/assistant');
  await expect(page.getByRole('heading', { level: 1, name: t('en', 'assistant.title') })).toBeVisible();
  await expect(page.locator('p.mode')).toContainText(/DEMO/i);
  await page.getByRole('button', { name: t('en', 'assistant.starter.status') }).click();
  await page.getByRole('button', { name: t('en', 'assistant.ask') }).click();
  await expect(page.getByText('Demo response — not generated by a live AI model')).toBeVisible({ timeout: 20_000 });
});

test('supplier contact cannot open assistant', async ({ page }) => {
  await page.goto('/assistant');
  await expect(page).toHaveURL(/\/sign-in/);
  await page.locator('#sign-in-email').fill('contact.skf@demo.local');
  await page.locator('#sign-in-password').fill(process.env['DEMO_USER_PASSWORD']!);
  await page.getByRole('button', { name: t('en', 'auth.signIn.submit') }).click();
  await expect(page).not.toHaveURL(/\/sign-in/);
  await page.goto('/assistant');
  await expect(page.getByRole('heading', { name: t('en', 'notFound.title') })).toBeVisible();
});
